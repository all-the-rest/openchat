import { spawnSync } from "node:child_process"
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterAll, describe, expect, it } from "vitest"
import { createRunner } from "../src/runner"

/**
 * Opt-in integration against a real interpreter and the real toolchain:
 *
 *   OPENCHAT_PYTHON_INTEGRATION=1 pnpm --filter @openchat/python-tool test
 *
 * It skips on a machine without the dependencies (and is skipped by default),
 * so the default suite never needs Python, never reaches the network and never
 * depends on a `.venv`. The fixtures are generated by the same interpreter with
 * python-docx, openpyxl, python-pptx and reportlab; markitdown then reads them
 * back through the runner boundary.
 */

const PYTHON = process.env.OPENCHAT_PYTHON?.trim() || process.env.PYTHON?.trim() || "python3"
const ENABLED = process.env.OPENCHAT_PYTHON_INTEGRATION === "1"
const IMPORTS = "import docx, openpyxl, pptx, reportlab, markitdown, magika, onnxruntime"
const IMPORTS_OK = spawnSync(PYTHON, ["-c", IMPORTS], { encoding: "utf8" }).status === 0

const FIXTURES = `
import os
from docx import Document
from openpyxl import Workbook
from pptx import Presentation
from reportlab.pdfgen import canvas

root = os.environ["FIXTURE_DIR"]

document = Document()
document.add_paragraph("Integration paragraph")
document.save(os.path.join(root, "fixture.docx"))

workbook = Workbook()
sheet = workbook.active
sheet.append(["Item", "Amount"])
sheet.append(["Coffee", 4.5])
workbook.save(os.path.join(root, "fixture.xlsx"))

slides = Presentation()
slide = slides.slides.add_slide(slides.slide_layouts[1])
slide.shapes.title.text = "Integration deck"
slides.save(os.path.join(root, "fixture.pptx"))

pdf = canvas.Canvas(os.path.join(root, "fixture.pdf"))
pdf.drawString(72, 720, "Integration PDF")
pdf.save()
`

const temporary: string[] = []

async function workspace(): Promise<string> {
  const directory = await mkdtemp(join(tmpdir(), "python-tool-integration-"))
  temporary.push(directory)
  return directory
}

afterAll(async () => {
  for (const directory of temporary.splice(0)) {
    await rm(directory, { recursive: true, force: true })
  }
})

describe.skipIf(!ENABLED || !IMPORTS_OK)("real Python document toolchain", () => {
  it("converts DOCX, XLSX, PPTX and PDF to Markdown", async () => {
    const directory = await workspace()
    const created = spawnSync(PYTHON, ["-c", FIXTURES], {
      env: { ...process.env, FIXTURE_DIR: directory },
      encoding: "utf8",
    })
    expect(created.status, created.stderr).toBe(0)

    const run = createRunner({ python: PYTHON })
    const expected: Array<[string, string]> = [
      ["fixture.docx", "Integration paragraph"],
      ["fixture.xlsx", "Coffee"],
      ["fixture.pptx", "Integration deck"],
      ["fixture.pdf", "Integration PDF"],
    ]

    for (const [filename, text] of expected) {
      const data = await readFile(join(directory, filename))
      const result = await run("read_document", {
        filename,
        data: data.toString("base64"),
      })
      expect(result, `${filename} must convert`).toMatchObject({ ok: true })
      if (!result.ok) continue
      expect(result.value.filename).toBe(filename.replace(/\.[a-z]+$/, ".md"))
      expect(result.value.mediaType).toBe("text/markdown")
      expect(result.value.data.toString("utf8")).toContain(text)
    }
  })

  it("maps a corrupt file to the stable parse code without a traceback", async () => {
    const directory = await workspace()
    const workspaceRoot = await workspace()
    const broken = join(directory, "broken.docx")
    await writeFile(broken, "this is not an OOXML package")
    const data = await readFile(broken)

    const run = createRunner({ python: PYTHON, tempRoot: workspaceRoot })
    const result = await run("read_document", {
      filename: "broken.docx",
      data: data.toString("base64"),
    })

    expect(result).toEqual({ ok: false, error: "parse: the document could not be read" })
    expect(JSON.stringify(result)).not.toContain("Traceback")
    // The runner removes its workspace on the failure path too.
    expect(await readdir(workspaceRoot)).toEqual([])
  })
})

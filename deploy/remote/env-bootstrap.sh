#!/usr/bin/env bash
#
# One-time bootstrap of the host-only stack environment (issue #20).
#
# Runs on the VPS through `ssh … bash -s` from deploy/remote/deploy.sh and
# writes `/opt/stacks/openchat/.env` **only when it does not exist**. An
# existing file is never read into an argument, rewritten or replaced: rotation
# is an owner action (see docs/implementation/20-remote-deploy.md).
#
# What comes from where:
#   AUTH_USER  -> OPENCHAT_USER              read from the predecessor's .env
#   AUTH_HASH  -> OPENCHAT_PASSWORD_HASH     the bcrypt digest, never the
#                                            plaintext, single-quoted because
#                                            Compose expands `$…` in env files
#   new        -> SESSION_SECRET, CODE_TICKET_SECRET, ARTIFACT_SIGNING_KEY,
#                 OPENCODE_PASSWORD          `openssl rand`
#   new        -> ARTIFACT_INTERNAL_TOKEN    `openssl rand -hex 32`
#   new        -> DOCUMENTS_TOKEN            `openssl rand -hex 32`
#
# No value is printed by this script: it names the file, the mode and the keys,
# never a secret. `set -x` is deliberately absent and must stay absent.

set -euo pipefail

PROG=$(basename "$0")
# The deploy script runs this file from the synced source tree, so the sibling
# filter is reachable. If it were piped over stdin, BASH_SOURCE would be empty.
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)
STACK_DIR=/opt/stacks/openchat
PREDECESSOR_ENV=/opt/stacks/dev-vm/.env
DOMAIN=""
DRY_RUN=0

usage() {
  cat <<'EOF'
Bootstrap /opt/stacks/openchat/.env once.

Usage:
  env-bootstrap.sh --domain example.com [options]

Options:
  --stack-dir DIR         stack root (default: /opt/stacks/openchat)
  --predecessor-env FILE  where AUTH_USER and AUTH_HASH live
                          (default: /opt/stacks/dev-vm/.env)
  --domain DOMAIN         base domain; origins become chat./code./artifacts.
  --dry-run               print what would be read and written, write nothing
  --help

Refuses to overwrite an existing .env. Prints no value, only key names.
EOF
}

die() {
  printf '%s: %s\n' "$PROG" "$*" >&2
  exit 1
}

note() {
  printf '%s\n' "$*"
}

parse_args() {
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --stack-dir) [ "$#" -ge 2 ] || die "$1 needs a value"; STACK_DIR=$2; shift 2 ;;
      --predecessor-env) [ "$#" -ge 2 ] || die "$1 needs a value"; PREDECESSOR_ENV=$2; shift 2 ;;
      --domain) [ "$#" -ge 2 ] || die "$1 needs a value"; DOMAIN=$2; shift 2 ;;
      --dry-run) DRY_RUN=1; shift ;;
      --help) usage; exit 0 ;;
      *) die "unknown argument: $1" ;;
    esac
  done
  [ -n "$DOMAIN" ] || die "--domain is required"
  case "$DOMAIN" in
    *[!a-z0-9.-]*) die "--domain must be a bare DNS name (lowercase letters, digits, dots, dashes)" ;;
  esac
}

# Reads one value without echoing it and without letting a `#` start a comment
# in the middle of a digest. Single quotes around the file value are stripped.
predecessor_value() {
  sed -n "s/^$1=//p" "$PREDECESSOR_ENV" | tail -n 1 | tr -d "'\""
}

# Compose interpolates `$` in env-file values, so a copied credential has to be
# escaped (`$2b$12$abc` -> `$$2b$$12$$abc`). The filter is idempotent and never
# prints the value anywhere but into the .env file below.
escape_env_value() {
  bash "$HERE/env-value.sh"
}

main() {
  parse_args "$@"
  local env_file="$STACK_DIR/.env"

  if [ -e "$env_file" ]; then
    note "env: kept $env_file (it exists; a deploy never overwrites it)"
    note "env: rotate by editing the file in place and recreating the stack; keys:"
    note "env:   SESSION_SECRET, CODE_TICKET_SECRET, ARTIFACT_SIGNING_KEY,"
    note "env:   OPENCODE_PASSWORD, ARTIFACT_INTERNAL_TOKEN, DOCUMENTS_TOKEN,"
    note "env:   OPENCHAT_PASSWORD_HASH"
    return 0
  fi

  [ -r "$PREDECESSOR_ENV" ] || die "cannot read $PREDECESSOR_ENV; AUTH_USER and AUTH_HASH must come from there"
  local auth_user auth_hash
  auth_user=$(predecessor_value AUTH_USER)
  auth_hash=$(predecessor_value AUTH_HASH | escape_env_value)
  [ -n "$auth_user" ] || die "$PREDECESSOR_ENV has no AUTH_USER"
  [ -n "$auth_hash" ] || die "$PREDECESSOR_ENV has no AUTH_HASH"
  case "$auth_hash" in
    \$\$2a\$\$*|\$\$2b\$\$*|\$\$2y\$\$*) ;;
    *) die "$PREDECESSOR_ENV AUTH_HASH is not a bcrypt digest; set OPENCHAT_PASSWORD_HASH by hand instead" ;;
  esac

  if [ "$DRY_RUN" -eq 1 ]; then
    note "would: read AUTH_USER and AUTH_HASH from $PREDECESSOR_ENV (values not shown)"
    note "would: write $env_file (0600) with APP_ORIGIN=https://chat.$DOMAIN and generated secrets"
    return 0
  fi

  command -v openssl >/dev/null 2>&1 || die "openssl is required to generate the secrets"

  mkdir -p "$STACK_DIR"
  umask 077
  local tmp="$env_file.tmp"
  {
    printf '# Generated by deploy/remote/deploy.sh on %s. Mode 0600; never commit.\n' "$(date -u +%FT%TZ)"
    printf '# One credential; the bcrypt digest is the predecessor AUTH_HASH, the\n'
    printf '# plaintext never reached this host.\n'
    printf 'APP_ORIGIN=https://chat.%s\n' "$DOMAIN"
    printf 'CODE_HOST_ORIGIN=https://code.%s\n' "$DOMAIN"
    printf 'ARTIFACT_HOST_URL=https://artifacts.%s\n' "$DOMAIN"
    printf 'BFF_PORT=8787\n'
    printf 'ARTIFACT_PORT=4100\n'
    printf 'AUTH_MODE=session\n'
    printf 'OPENCHAT_USER=%s\n' "$auth_user"
    # `$` is doubled: Compose interpolates env-file values, so an unescaped
    # `$2b$12$ab…` reach the BFF as `$2b$12` and login can never succeed.
    printf 'OPENCHAT_PASSWORD_HASH=%s\n' "$auth_hash"
    printf 'OPENCHAT_PASSWORD=\n'
    printf 'SESSION_SECRET=%s\n' "$(openssl rand -base64 32)"
    printf 'SESSION_TTL_SECONDS=604800\n'
    printf 'COOKIE_SECURE=1\n'
    printf 'ALLOW_INSECURE_COOKIE=0\n'
    # Caddy overwrites X-Forwarded-For with the client address it observed.
    printf 'TRUST_PROXY=1\n'
    printf 'OPENCODE_URL=http://opencode:4096\n'
    printf 'OPENCODE_USERNAME=opencode\n'
    printf 'OPENCODE_PASSWORD=%s\n' "$(openssl rand -base64 24)"
    printf 'CODE_TICKET_SECRET=%s\n' "$(openssl rand -base64 32)"
    printf 'CODE_TICKET_TTL_SECONDS=60\n'
    printf 'CODE_SESSION_TTL_SECONDS=43200\n'
    printf 'ARTIFACT_SIGNING_KEY=%s\n' "$(openssl rand -base64 32)"
    printf 'ARTIFACT_INTERNAL_TOKEN=%s\n' "$(openssl rand -hex 32)"
    printf 'DOCUMENTS_TOKEN=%s\n' "$(openssl rand -hex 32)"
    printf 'STT_URL=\n'
    printf 'STT_API_KEY=\n'
  } > "$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$env_file"

  note "env: wrote $env_file (0600); values were not printed"
  note "env: keys: APP_ORIGIN CODE_HOST_ORIGIN ARTIFACT_HOST_URL BFF_PORT ARTIFACT_PORT"
  note "env:       AUTH_MODE OPENCHAT_USER OPENCHAT_PASSWORD_HASH SESSION_SECRET"
  note "env:       SESSION_TTL_SECONDS COOKIE_SECURE ALLOW_INSECURE_COOKIE TRUST_PROXY"
  note "env:       OPENCODE_URL OPENCODE_USERNAME OPENCODE_PASSWORD CODE_TICKET_SECRET"
  note "env:       CODE_TICKET_TTL_SECONDS CODE_SESSION_TTL_SECONDS ARTIFACT_SIGNING_KEY"
  note "env:       ARTIFACT_INTERNAL_TOKEN DOCUMENTS_TOKEN STT_URL STT_API_KEY"
}

main "$@"
